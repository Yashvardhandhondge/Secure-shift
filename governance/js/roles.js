/* =========================================================
   Governance - roles.js  (governance/roles.html?id=...)
   ========================================================= */
(function () {
  "use strict";
  if (!SS.session.current) return;

  var roles = SS.GOV.load("roles");
  var rules = SS.GOV.load("rules");
  var wanted = SS.param("id");

  // If we arrive from an identity that has no role yet, generate one now
  if (wanted && !roles.some(function (r) { return r.id === wanted; })) {
    var idName = wanted.replace(/-custom-role$/, "");
    var idt = SS.GOV.identities.filter(function (i) { return i.id === idName; })[0];
    if (idt) {
      var det = SS.GOV.getDetail(idt);
      roles.push({ id: wanted, identity: idt.id, original: idt.role + " (" + idt.scope + ")", scope: det.suggestedScope, actions: idt.used, reviewed: false, rare: [] });
      SS.GOV.save("roles", roles);
      SS.ui.toast("New role generated for " + idt.id, "key");
    }
  }
  var current = roles.filter(function (r) { return r.id === wanted; })[0] || roles[0];
  SS.$("#chk-baseline").checked = !!rules.baselineRead;

  function actionsFor(role) {
    var idt = SS.GOV.identities.filter(function (i) { return i.id === role.identity; })[0];
    var acts = SS.GOV.getDetail(idt).usedPerms.map(function (p) { return p.action; });
    var write = acts.filter(function (a) { return !/\/read$/.test(a); });
    var read = acts.filter(function (a) { return /\/read$/.test(a); });
    return SS.$("#chk-baseline").checked ? write.concat(read) : write;
  }

  function roleJson(role) {
    return {
      Name: role.id,
      IsCustom: true,
      Description: "Least-privilege role generated by SecureShift Cloud Governance for " + role.identity,
      Actions: actionsFor(role),
      NotActions: [],
      AssignableScopes: ["/subscriptions/00000000-0000-0000-0000-000000000000/resourceGroups/" + role.scope]
    };
  }

  function renderList() {
    SS.$("#role-count").textContent = roles.filter(function (r) { return r.reviewed; }).length + " of " + roles.length + " reviewed";
    SS.$("#role-list").innerHTML = roles.map(function (r) {
      return '<button class="list-item ' + (r.id === current.id ? "active" : "") + '" data-role="' + SS.esc(r.id) + '"><span><b class="mono small">' +
             SS.esc(r.id) + "</b><small>" + SS.esc((SS.GOV.byId(r.identity) || {}).name || r.identity) + " · " + SS.esc(r.original) + "</small></span>" +
             (r.reviewed ? '<span class="badge badge-solid">Reviewed</span>' : '<span class="badge badge-soft">Pending</span>') + "</button>";
    }).join("");
    SS.$$("[data-role]").forEach(function (b) {
      b.addEventListener("click", function () {
        current = roles.filter(function (r) { return r.id === b.getAttribute("data-role"); })[0];
        render();
      });
    });
  }

  function render() {
    renderList();
    var json = roleJson(current);
    SS.$("#r-title").innerHTML = '<span class="mono" style="font-size:15px">' + SS.esc(current.id) + "</span>";
    SS.$("#r-status").innerHTML = current.reviewed ? '<span class="badge badge-solid">Reviewed</span>' : '<span class="badge badge-soft">Pending review</span>';
    SS.$("#r-original").textContent = current.original;
    SS.$("#r-scope").textContent = current.scope + " (Resource Group)";
    SS.$("#r-actions").textContent = current.actions;
    SS.$("#r-json").textContent = JSON.stringify(json, null, 2);
    SS.$("#az-cmd").textContent = "az role definition create --role-definition " + current.id + ".json";
    SS.$("#btn-reviewed").innerHTML = SS.icon(current.reviewed ? "refresh" : "check") + (current.reviewed ? "Mark as Pending" : "Mark as Reviewed");
    SS.$("#rare-box").innerHTML = current.rare.length
      ? '<b class="row">' + SS.icon("alert") + "Rare / Review Actions (" + current.rare.length + ")</b><ul>" +
        current.rare.map(function (r) { return '<li class="mono small">' + SS.esc(r) + "</li>"; }).join("") + "</ul>" +
        '<p class="small muted mt">Used fewer than ' + rules.rareThreshold + " times - confirm before keeping them in the role.</p>"
      : '<b class="row">' + SS.icon("checkCircle") + "No rare actions</b><p class='small muted'>Every action in this role was used regularly.</p>";
    history.replaceState(null, "", "roles.html?id=" + encodeURIComponent(current.id));
  }

  SS.$("#chk-baseline").addEventListener("change", render);
  SS.$("#btn-download").addEventListener("click", function () {
    SS.ui.download(current.id + ".json", JSON.stringify(roleJson(current), null, 2));
  });
  SS.$("#btn-copy-az").addEventListener("click", function () { SS.ui.copy(SS.$("#az-cmd").textContent); });
  SS.$("#btn-reviewed").addEventListener("click", function () {
    current.reviewed = !current.reviewed;
    SS.GOV.save("roles", roles);
    render();
    SS.ui.toast(current.reviewed ? current.id + " marked as reviewed" : current.id + " moved back to pending");
  });

  render();
})();
